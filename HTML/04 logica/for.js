//   entre os laços de repetições da logica de programação, e por pro la For era o mais utilizado por economizar espaço  e  trazer praticidade  para o desenvolvimento 

//  Para utilizar o For é necessário ter um contador para que delimitemos a quantidade de vezes que algo que sera repetido, a estrutura do for recebe inicialização, condições e incremento .
console.log(" Vou contar  ate 10 e falar Alice Ravi ");
//    inicializção; condi incremento 
for ( let i = 0; i <=10;  i+2  ) {
    console.log( "i" );
} 
console.log( "  Alice e Ravi  ");
